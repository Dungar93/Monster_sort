// Helper to select a subset of monsters by IDs
function selectMonsters(ids: string[]): Monster[] {
  return ids.map((id) => {
    const found = MONSTER_CATALOG.find((m) => m.id === id);
    if (!found) throw new Error(`Monster with ID ${id} not found in catalog`);
    return found;
  });
}

